/**
 * 生成追加到 system prompt 的角色块（自我模型 + 示范）。
 */
export function characterBlock(card: CharacterCard): string {
  return (
    `【角色自我认知 · 始终在线】\n` +
    `${card.selfModel}\n\n` +
    `【表达示范 · 群聊口吻（参考，但每次都自然说出，不要照抄）】\n` +
    `${card.exampleDialogue}`
  );
}
