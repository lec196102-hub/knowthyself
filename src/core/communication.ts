/** 把单条气质沟通画像格式化成可注入 prompt 的文本 */
function formatCommEntry(t: TemperamentType, e: CommStyleEntry): string {
  return (
    `【${TYPE_LABELS[t]}倾向 · 他最爱听的话术】\n` +
    `· 特质：${e.trait}\n` +
    `· 他最爱听：${e.loves}\n` +
    `· 他最烦：${e.hates}\n` +
    `· 适配话术：${e.tactics}`
  );
}

/**
 * 由气质画像生成「这个用户爱听什么话」的沟通适配文本。
 * 用 primary(0.7)/secondary(0.3) 混合，与气质风格调制同口径；
 * 低密度气质不计入（与 getStyleModulation 一致）。
 */
export function buildCommStyle(profile: TemperamentProfile): string {
  const { primary, secondary, intensities } = profile;
  const weight = (t: TemperamentType): number => {
    if (t === primary) return secondary ? 0.7 : 1.0;
    if (t === secondary) return 0.3;
    return 0;
  };
  const parts: string[] = [];
  for (const t of TYPE_ORDER) {
    const w = weight(t);
    if (w > 0 && intensities[t] !== "low") {
      parts.push(formatCommEntry(t, COMM_STYLE_BY_TEMPERAMENT[t]));
    }
  }
  if (parts.length === 0) {
    return formatCommEntry(primary, COMM_STYLE_BY_TEMPERAMENT[primary]);
  }
  return parts.join("\n\n");
}

