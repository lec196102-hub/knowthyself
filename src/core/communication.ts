/**
 * 沟通底层逻辑 · 源自经典心理学 / 话术书籍的提炼（精简·去重）
 *
 * 资料依据（仅作方法来源，非逐字引用）：
 *  - 马歇尔·卢森堡《非暴力沟通》(NVC)：观察→感受→需要→请求，聚焦需求而非指责，请求≠命令
 *  - 帕特森等《关键对话》：紧盯目标、先共情再谈事、对比法（先说不要什么再说要什么）
 *  - 克里斯·沃斯《掌控谈话》(FBI 谈判)：重复+沉默、标注(mirroring)、校准问题把球踢回、用「不」比「是」安全
 *  - 维吉尼亚·萨提亚 家庭治疗：冰山模型（行为→应对→感受→观点→期待→渴望→自我）、一致性沟通（我-你-情境）
 *  - 吴秀香《好感话术》：首因效应、喜好/相似、具体赞美、积极关注
 *  - 阮琦《魔鬼沟通学》：真实自我、按场景拆解（破冰/表达/关系/冲突）
 *  - 卡耐基《人性的弱点》：真诚赞美、让对方觉得自己重要
 *
 * 设计原则：
 *  1) 通用底理 COMMUNICATION_PRINCIPLES → 注入三位人格的 base prompt（每次对话都在）
 *  2) 气质适配 COMM_STYLE_BY_TEMPERAMENT / buildCommStyle → 由已推断的「四气质」驱动，
 *     告诉三我「这个用户最爱听什么话」。app 已能从问卷/语言推断四气质，天然就是「用户偏好」信号源。
 */

